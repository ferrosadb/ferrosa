//! The converter: a [`Program`] to AssemblyScript implementing the `ferrosa:plpgsql` `routine`
//! world, which `ferrosa-udf` compiles in process and componentizes.
//!
//! The generated code is the interpreter's algorithm over the same slots, written against the
//! canonical ABI by hand (the AssemblyScript toolchain has no component bindings):
//!
//! * each slot is a 16-byte `value` record (`type-oid` u32 at 0, `option<string>`
//!   discriminant at 4, string pointer at 8, length at 12) in one array at `__slots`;
//! * each expression's SQL is a static UTF-8 data segment; its parameters are a fresh
//!   `list<value>` copied from the referenced slots;
//! * a host error, or a runtime error the code raises itself, sets `__failed` and the error
//!   strings, and every fallible step is followed by `if (__failed) return __err();`.
//!
//! Every allocation is a bump allocation in the stub runtime, reclaimed in one shot by the
//! post-return function. Runtime errors use the same SQLSTATE and text as the interpreter
//! (`crate::messages`), so the two fail identically.

use std::fmt::Write as _;

use crate::ast::{Cond, Expr, Program, RoutineKind, Stmt, VarId, VarKind};
use crate::interp::bare_variable;
use crate::messages::{self, RuntimeError};
use crate::FETCH_BATCH;

/// The core-module import namespace of the host interface (`ferrosa:plpgsql/host@0.1.0`).
pub const HOST_MODULE: &str = "ferrosa:plpgsql/host@0.1.0";

/// Convert `program` to AssemblyScript source exporting `call`, `cabi_realloc` and
/// `cabi_post_call`. Total on the parsed subset: every statement has a translation.
pub fn convert(program: &Program) -> String {
    let mut out = String::new();
    out.push_str(&prelude());
    let mut gen = Gen {
        program,
        out: String::new(),
        next: 0,
    };
    gen.entry();
    out.push_str(&gen.out);
    out
}

/// AssemblyScript bytes of `s` as a static data segment expression and its length.
fn data(s: &str) -> (String, usize) {
    if s.is_empty() {
        return ("0".into(), 0);
    }
    let bytes: Vec<String> = s.bytes().map(|b| b.to_string()).collect();
    (
        format!("<i32>memory.data<u8>([{}])", bytes.join(", ")),
        s.len(),
    )
}

/// `__fail(...)` for a runtime error constant.
fn fail_call(e: RuntimeError) -> String {
    let (state, state_len) = data(e.0);
    let (msg, msg_len) = data(e.1);
    format!("__fail({state}, {state_len}, {msg}, {msg_len})")
}

/// The helpers every routine uses: host imports, ABI glue, evaluation primitives.
fn prelude() -> String {
    let m = HOST_MODULE;
    let batch = FETCH_BATCH;
    let not_one = fail_call(messages::NOT_ONE_COLUMN);
    let cast = fail_call(messages::ASSIGNMENT_CAST);
    let not_bool = fail_call(messages::NOT_BOOLEAN);
    let empty_channel = fail_call(messages::EMPTY_CHANNEL);
    format!(
        r#"// --- generated by ferrosa-plpgsql: do not edit ---
@external("{m}", "query")
declare function __h_query(sql: i32, sqlLen: i32, params: i32, paramsLen: i32, ret: i32): void;
@external("{m}", "fetch")
declare function __h_fetch(cursor: i32, max: i32, ret: i32): void;
@external("{m}", "close")
declare function __h_close(cursor: i32): void;
@external("{m}", "execute")
declare function __h_execute(sql: i32, sqlLen: i32, params: i32, paramsLen: i32, ret: i32): void;
@external("{m}", "notify")
declare function __h_notify(ch: i32, chLen: i32, pl: i32, plLen: i32, ret: i32): void;

let __slots: i32 = 0;
let __ret: i32 = 0;
let __failed: bool = false;
let __eState: i32 = 0;
let __eStateLen: i32 = 0;
let __eMsg: i32 = 0;
let __eMsgLen: i32 = 0;
let __rowsLen: i32 = 0;
let __rowLen: i32 = 0;
let __found: bool = false;

function __alloc(n: i32): i32 {{
  return <i32>heap.alloc(<usize>n);
}}
export function cabi_realloc(ptr: i32, oldSize: i32, align: i32, newSize: i32): i32 {{
  let p = __alloc(newSize);
  if (ptr != 0) memory.copy(<usize>p, <usize>ptr, <usize>(oldSize < newSize ? oldSize : newSize));
  return p;
}}
export function cabi_post_call(ret: i32): void {{
  __reset();
}}
function __fail(state: i32, stateLen: i32, msg: i32, msgLen: i32): void {{
  __failed = true;
  __eState = state;
  __eStateLen = stateLen;
  __eMsg = msg;
  __eMsgLen = msgLen;
}}
function __hostErr(at: i32): void {{
  __fail(load<i32>(at), load<i32>(at + 4), load<i32>(at + 8), load<i32>(at + 12));
}}
function __err(): i32 {{
  let o = __alloc(24);
  store<u8>(o, 1);
  store<i32>(o + 4, __eState);
  store<i32>(o + 8, __eStateLen);
  store<i32>(o + 12, __eMsg);
  store<i32>(o + 16, __eMsgLen);
  return o;
}}
function __okSome(v: i32): i32 {{
  let o = __alloc(24);
  store<u8>(o, 0);
  store<u8>(o + 4, 1);
  memory.copy(<usize>(o + 8), <usize>v, 16);
  return o;
}}
function __okNone(): i32 {{
  let o = __alloc(24);
  store<u8>(o, 0);
  store<u8>(o + 4, 0);
  return o;
}}
function __null(dst: i32, oid: u32): void {{
  store<u32>(dst, oid);
  store<u8>(dst + 4, 0);
}}
function __query(sql: i32, sqlLen: i32, p: i32, n: i32): i32 {{
  __h_query(sql, sqlLen, p, n, __ret);
  if (load<u8>(__ret) != 0) {{
    __hostErr(__ret + 4);
    return 0;
  }}
  return load<i32>(__ret + 4);
}}
function __fetch(c: i32, max: i32): i32 {{
  __h_fetch(c, max, __ret);
  if (load<u8>(__ret) != 0) {{
    __hostErr(__ret + 4);
    __rowsLen = 0;
    return 0;
  }}
  __rowsLen = load<i32>(__ret + 8);
  return load<i32>(__ret + 4);
}}
// The first row of a query (one row read, then closed): its value list, with __found and
// __rowLen set.
function __first(sql: i32, sqlLen: i32, p: i32, n: i32): i32 {{
  __found = false;
  let c = __query(sql, sqlLen, p, n);
  if (__failed) return 0;
  let rows = __fetch(c, 1);
  let count = __rowsLen;
  __h_close(c);
  if (__failed || count == 0) return 0;
  __found = true;
  __rowLen = load<i32>(rows + 4);
  return load<i32>(rows);
}}
function __scalar(sql: i32, sqlLen: i32, p: i32, n: i32, dst: i32): void {{
  let row = __first(sql, sqlLen, p, n);
  if (__failed) return;
  if (!__found) {{
    __null(dst, 0);
    return;
  }}
  if (__rowLen != 1) {{
    {not_one};
    return;
  }}
  memory.copy(<usize>dst, <usize>row, 16);
}}
function __perform(sql: i32, sqlLen: i32, p: i32, n: i32): void {{
  let c = __query(sql, sqlLen, p, n);
  if (__failed) return;
  // Bounded by the host: each batch holds at most {batch} rows and the query ends with an
  // empty batch.
  while (true) {{
    __fetch(c, {batch});
    if (__failed || __rowsLen == 0) break;
  }}
  __h_close(c);
}}
function __execute(sql: i32, sqlLen: i32, p: i32, n: i32): void {{
  __h_execute(sql, sqlLen, p, n, __ret);
  if (load<u8>(__ret) != 0) __hostErr(__ret + 8);
}}
function __textLike(oid: u32): bool {{
  return oid == 25 || oid == 1043;
}}
function __fit(v: i32, oid: u32): void {{
  if (load<u8>(v + 4) == 0) {{
    store<u32>(v, oid);
    return;
  }}
  let have = load<u32>(v);
  if (have == oid || (__textLike(have) && __textLike(oid))) {{
    store<u32>(v, oid);
    return;
  }}
  {cast};
}}
function __test(v: i32): bool {{
  if (load<u8>(v + 4) == 0) return false;
  if (load<u32>(v) != 16) {{
    {not_bool};
    return false;
  }}
  return load<i32>(v + 12) == 1 && load<u8>(load<i32>(v + 8)) == 0x74;
}}
function __notify(ch: i32, pl: i32): void {{
  if (load<u8>(ch + 4) == 0 || load<i32>(ch + 12) == 0) {{
    {empty_channel};
    return;
  }}
  let plPtr: i32 = 0;
  let plLen: i32 = 0;
  if (load<u8>(pl + 4) != 0) {{
    plPtr = load<i32>(pl + 8);
    plLen = load<i32>(pl + 12);
  }}
  __h_notify(load<i32>(ch + 8), load<i32>(ch + 12), plPtr, plLen, __ret);
  if (load<u8>(__ret) != 0) __hostErr(__ret + 4);
}}
"#
    )
}

const CHECK: &str = "if (__failed) return __err();";

struct Gen<'p> {
    program: &'p Program,
    out: String,
    next: usize,
}

impl Gen<'_> {
    fn fresh(&mut self, prefix: &str) -> String {
        self.next += 1;
        format!("{prefix}{}", self.next)
    }

    fn line(&mut self, depth: usize, text: &str) {
        for _ in 0..depth {
            self.out.push_str("  ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn slot(id: VarId) -> String {
        format!("(__slots + {})", id.0 * 16)
    }

    fn entry(&mut self) {
        self.line(0, "export function call(argsPtr: i32, argsLen: i32, tDisc: i32, opPtr: i32, opLen: i32, newDisc: i32, newPtr: i32, newLen: i32, oldDisc: i32, oldPtr: i32, oldLen: i32): i32 {");
        self.line(1, "__failed = false;");
        self.line(1, "__ret = __alloc(24);");
        let n = self.program.variables.len().max(1);
        self.line(1, &format!("__slots = __alloc(16 * {n});"));
        self.call_checks();
        self.bind_slots();
        for decl in &self.program.declarations {
            if let Some(expr) = &decl.default {
                self.assign(1, decl.var, expr);
            }
        }
        for stmt in &self.program.body {
            self.stmt(1, stmt);
        }
        match self.program.kind {
            RoutineKind::Do | RoutineKind::Void => self.line(1, "return __okNone();"),
            RoutineKind::Scalar(_) | RoutineKind::Trigger => {
                let fail = fail_call(messages::NO_RETURN);
                self.line(1, &format!("{fail};"));
                self.line(1, "return __err();");
            }
        }
        self.line(0, "}");
    }

    /// The same checks, in the same order, as the interpreter's `initial_slots`.
    fn call_checks(&mut self) {
        let args = fail_call(messages::ARGUMENT_SHAPE);
        self.line(
            1,
            &format!(
                "if (argsLen != {}) {{ {args}; return __err(); }}",
                self.program.arg_count
            ),
        );
        if self.program.kind != RoutineKind::Trigger {
            return;
        }
        let not_trigger = fail_call(messages::NOT_A_TRIGGER_CALL);
        self.line(
            1,
            &format!("if (tDisc == 0) {{ {not_trigger}; return __err(); }}"),
        );
        let shape = fail_call(messages::ROW_SHAPE);
        let (new_n, old_n) = (
            self.program.new_fields().len(),
            self.program.old_fields().len(),
        );
        self.line(
            1,
            &format!("if (newDisc != 0 && newLen != {new_n}) {{ {shape}; return __err(); }}"),
        );
        self.line(
            1,
            &format!("if (oldDisc != 0 && oldLen != {old_n}) {{ {shape}; return __err(); }}"),
        );
    }

    fn bind_slots(&mut self) {
        let (mut new_i, mut old_i) = (0usize, 0usize);
        for (i, var) in self.program.variables.iter().enumerate() {
            let slot = Self::slot(VarId(i));
            let text = match &var.kind {
                VarKind::Local => format!("__null({slot}, {});", var.type_oid.unwrap_or(0)),
                VarKind::Argument(a) => format!("memory.copy(<usize>{slot}, <usize>(argsPtr + {}), 16);", a * 16),
                VarKind::NewField(_) => {
                    new_i += 1;
                    Self::field(&slot, "new", new_i - 1)
                }
                VarKind::OldField(_) => {
                    old_i += 1;
                    Self::field(&slot, "old", old_i - 1)
                }
                VarKind::TgOp => format!(
                    "store<u32>({slot}, 25); store<u8>({slot} + 4, 1); store<i32>({slot} + 8, opPtr); store<i32>({slot} + 12, opLen);"
                ),
            };
            self.line(1, &text);
        }
    }

    fn field(slot: &str, which: &str, j: usize) -> String {
        format!(
            "if ({which}Disc != 0) memory.copy(<usize>{slot}, <usize>({which}Ptr + {}), 16); else __null({slot}, 0);",
            j * 16
        )
    }

    /// Build `expr`'s parameter list; returns `(pointer variable, count)`.
    fn params(&mut self, depth: usize, expr: &Expr) -> (String, usize) {
        if expr.refs.is_empty() {
            return ("0".into(), 0);
        }
        let p = self.fresh("p");
        self.line(
            depth,
            &format!("let {p} = __alloc({});", expr.refs.len() * 16),
        );
        for (k, id) in expr.refs.iter().enumerate() {
            let slot = Self::slot(*id);
            self.line(
                depth,
                &format!("memory.copy(<usize>({p} + {}), <usize>{slot}, 16);", k * 16),
            );
        }
        (p, expr.refs.len())
    }

    /// Evaluate `expr` into a fresh 16-byte temporary; returns its name.
    fn eval(&mut self, depth: usize, expr: &Expr) -> String {
        let t = self.fresh("t");
        self.line(depth, &format!("let {t} = __alloc(16);"));
        if let Some(id) = bare_variable(expr) {
            let slot = Self::slot(id);
            self.line(
                depth,
                &format!("memory.copy(<usize>{t}, <usize>{slot}, 16);"),
            );
            return t;
        }
        let (p, n) = self.params(depth, expr);
        let (sql, len) = data(&format!("SELECT {}", expr.sql));
        self.line(depth, &format!("__scalar({sql}, {len}, {p}, {n}, {t});"));
        self.line(depth, CHECK);
        t
    }

    fn assign(&mut self, depth: usize, target: VarId, expr: &Expr) {
        self.line(depth, "{");
        let t = self.eval(depth + 1, expr);
        self.store(depth + 1, target, &t);
        self.line(depth, "}");
    }

    /// Fit temporary `t` to `target`'s declared type and store it.
    fn store(&mut self, depth: usize, target: VarId, t: &str) {
        if let Some(oid) = self.program.variables[target.0].type_oid {
            self.line(depth, &format!("__fit({t}, {oid});"));
            self.line(depth, CHECK);
        }
        let slot = Self::slot(target);
        self.line(
            depth,
            &format!("memory.copy(<usize>{slot}, <usize>{t}, 16);"),
        );
    }

    fn stmt(&mut self, depth: usize, stmt: &Stmt) {
        match stmt {
            Stmt::Assign { target, expr } => self.assign(depth, *target, expr),
            Stmt::If {
                branches,
                otherwise,
            } => self.if_chain(depth, branches, otherwise),
            Stmt::Return(expr) => self.ret(depth, expr.as_ref()),
            Stmt::Perform(expr) => {
                self.sql_call(depth, "__perform", &format!("SELECT {}", expr.sql), expr)
            }
            Stmt::Execute(expr) => self.sql_call(depth, "__execute", &expr.sql, expr),
            Stmt::Notify { channel, payload } => {
                self.line(depth, "{");
                let c = self.eval(depth + 1, channel);
                let p = self.eval(depth + 1, payload);
                self.line(depth + 1, &format!("__notify({c}, {p});"));
                self.line(depth + 1, CHECK);
                self.line(depth, "}");
            }
            Stmt::SelectInto { targets, query } => self.select_into(depth, targets, query),
            Stmt::Null => self.line(depth, "// NULL;"),
        }
    }

    fn sql_call(&mut self, depth: usize, helper: &str, sql: &str, expr: &Expr) {
        self.line(depth, "{");
        let (p, n) = self.params(depth + 1, expr);
        let (sql, len) = data(sql);
        self.line(depth + 1, &format!("{helper}({sql}, {len}, {p}, {n});"));
        self.line(depth + 1, CHECK);
        self.line(depth, "}");
    }

    fn ret(&mut self, depth: usize, expr: Option<&Expr>) {
        self.line(depth, "{");
        let Some(expr) = expr else {
            let t = self.fresh("t");
            self.line(depth + 1, &format!("let {t} = __alloc(16);"));
            self.line(depth + 1, &format!("__null({t}, 0);"));
            self.line(depth + 1, &format!("return __okSome({t});"));
            self.line(depth, "}");
            return;
        };
        let t = self.eval(depth + 1, expr);
        if let RoutineKind::Scalar(oid) = self.program.kind {
            self.line(depth + 1, &format!("__fit({t}, {oid});"));
            self.line(depth + 1, CHECK);
        }
        self.line(depth + 1, &format!("return __okSome({t});"));
        self.line(depth, "}");
    }

    /// Evaluate a condition into a fresh boolean; returns its name.
    fn test(&mut self, depth: usize, cond: &Cond) -> String {
        let c = self.fresh("c");
        match cond {
            Cond::Expr(expr) => {
                let t = self.eval(depth, expr);
                self.line(depth, &format!("let {c} = __test({t});"));
                self.line(depth, CHECK);
            }
            Cond::Exists { negated, query } => {
                let (p, n) = self.params(depth, query);
                let (sql, len) = data(&query.sql);
                self.line(depth, &format!("__first({sql}, {len}, {p}, {n});"));
                self.line(depth, CHECK);
                let cmp = if *negated { "!= true" } else { "== true" };
                self.line(depth, &format!("let {c} = __found {cmp};"));
            }
        }
        c
    }

    fn if_chain(&mut self, depth: usize, branches: &[(Cond, Vec<Stmt>)], otherwise: &[Stmt]) {
        let Some(((cond, body), rest)) = branches.split_first() else {
            for stmt in otherwise {
                self.stmt(depth, stmt);
            }
            return;
        };
        self.line(depth, "{");
        let c = self.test(depth + 1, cond);
        self.line(depth + 1, &format!("if ({c}) {{"));
        for stmt in body {
            self.stmt(depth + 2, stmt);
        }
        self.line(depth + 1, "} else {");
        self.if_chain(depth + 2, rest, otherwise);
        self.line(depth + 1, "}");
        self.line(depth, "}");
    }

    fn select_into(&mut self, depth: usize, targets: &[VarId], query: &Expr) {
        self.line(depth, "{");
        let (p, n) = self.params(depth + 1, query);
        let (sql, len) = data(&query.sql);
        let row = self.fresh("row");
        self.line(
            depth + 1,
            &format!("let {row} = __first({sql}, {len}, {p}, {n});"),
        );
        self.line(depth + 1, CHECK);
        self.line(depth + 1, "if (!__found) {");
        for target in targets {
            let oid = self.program.variables[target.0].type_oid.unwrap_or(0);
            let slot = Self::slot(*target);
            self.line(depth + 2, &format!("__null({slot}, {oid});"));
        }
        self.line(depth + 1, "} else {");
        let into = fail_call(messages::INTO_COLUMNS);
        self.line(
            depth + 2,
            &format!(
                "if (__rowLen != {}) {{ {into}; return __err(); }}",
                targets.len()
            ),
        );
        for (i, target) in targets.iter().enumerate() {
            let t = self.fresh("t");
            self.line(depth + 2, &format!("let {t} = __alloc(16);"));
            self.line(
                depth + 2,
                &format!("memory.copy(<usize>{t}, <usize>({row} + {}), 16);", i * 16),
            );
            self.store(depth + 2, *target, &t);
        }
        self.line(depth + 1, "}");
        self.line(depth, "}");
    }
}

/// Render for debugging: the generated source with line numbers.
pub fn numbered(source: &str) -> String {
    let mut out = String::new();
    for (i, line) in source.lines().enumerate() {
        let _ = writeln!(out, "{:4} {line}", i + 1);
    }
    out
}
