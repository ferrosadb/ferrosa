#!/usr/bin/env python3
"""Read the span table out of Aeneas-generated Lean.

Every item Aeneas emits carries a docstring like

    /-- [ferrosa_storage::count::RowCounter]
        Source: 'ferrosa-storage/src/count.rs', lines 61:0-65:1

which is Charon's record of where the item lives in the crate. This turns those docstrings into
`{lean name: {path, line, end_line}}`, so a red claim can name an implementation site without a
person maintaining a list of line numbers by hand.
"""

import json
import pathlib
import re
import sys

SPAN = re.compile(
    r"/--\s*\[(?P<name>[^\]]+)\]\s*:?\s*\n\s*Source: '(?P<path>[^']+)', lines (?P<a>\d+):\d+-(?P<b>\d+):\d+")
OUT = pathlib.Path(__file__).resolve().parent.parent / "specs/lean4/docs/rust_spans.json"


def main(paths):
    spans = {}
    for p in map(pathlib.Path, paths):
        for m in SPAN.finditer(p.read_text()):
            path = m.group("path")
            if path.startswith("/rustc/") or path.startswith("/rustlib/"):
                continue                      # core and std are not this repository
            spans[m.group("name")] = {
                "path": path,
                "line": int(m.group("a")),
                "end_line": int(m.group("b")),
            }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({
        "_doc": "Generated by scripts/rust_spans.py from the Aeneas extract. Lean item -> the Rust "
                "file and line range Charon recorded for it. Regenerate with "
                "scripts/lean_rust_extract.sh; never edit by hand.",
        "spans": dict(sorted(spans.items())),
    }, indent=1) + "\n")
    print(f"{len(spans)} spans -> {OUT}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("usage: rust_spans.py <generated.lean> ...")
    raise SystemExit(main(sys.argv[1:]))
