#!/usr/bin/env python3
"""Generate the Rust side of the Lean red ledger.

Reads `specs/lean4/build/specs.json` -- the documentation export, which carries every ledger claim
and, for the unmet ones, the witness theorem that proves the property absent -- and writes:

  red-ledger/src/reds.rs     the table: one `Red` per unmet claim, named by module and claim
  red-ledger/tests/reds.rs   tests that assert things about that table on every run

A red is data, not a test. The first version emitted one empty `#[ignore]`d test per red, which
shipped the join as 59 waivers; an ignored test that asserts nothing is a waiver whatever it is meant
to document. Closing a red is: write the real test in the crate that owns the code, then flip the
ledger item to `.met` in Lean, which drops the row from this table and moves the pinned count.

Usage:
    red_ledger.py            write both files
    red_ledger.py --check    exit 1 if either file on disk is not what the ledger produces
"""

import argparse
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent                      # ferrosa/
SPECS = ROOT / "specs/lean4/build/specs.json"
DATA = "red-ledger/src/reds.rs"
TESTS = "red-ledger/tests/reds.rs"

GENERATED = "// @generated by scripts/red_ledger.py from specs/lean4/build/specs.json — do not edit by hand.\n"

DATA_HEADER = GENERATED + """\
//
// One row per red item in the Lean ledgers. A row leaves this table when its Lean item is closed,
// which happens after the owning crate has a test that pins the claim.

/// One unmet claim of the Lean specification.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Red {
    /// `<module>__<claim>`, unique across the corpus; the name a closing test takes.
    pub name: &'static str,
    /// The Lean module whose ledger holds the claim.
    pub module: &'static str,
    /// The claim, verbatim from the ledger.
    pub claim: &'static str,
    /// Why the code does not meet it, verbatim from the ledger.
    pub why: &'static str,
    /// The theorem that proves the property absent.
    pub witness: &'static str,
}

pub const REDS: &[Red] = &[
"""

TESTS_TEMPLATE = GENERATED + """\
//
// Assertions about the red table. They run on every `cargo test`; nothing here is ignored.

use red_ledger::REDS;
use std::collections::HashSet;

/// **Every red is addressable.** Names are unique, so a closing test can take a red's name without
/// ambiguity, and each is a legal Rust identifier, so it can be that test's function name.
#[test]
fn red_names_are_unique_identifiers() {
    let mut seen = HashSet::new();
    for red in REDS {
        assert!(seen.insert(red.name), "two reds share the name {}", red.name);
        assert!(
            red.name.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_'),
            "{} is not a snake_case identifier",
            red.name
        );
    }
}

/// **Every red carries its evidence.** A red without a reason or a witness theorem is a claim
/// nobody can check, so the row is refused rather than carried.
#[test]
fn every_red_names_its_reason_and_witness() {
    for red in REDS {
        assert!(!red.claim.is_empty(), "{}: empty claim", red.name);
        assert!(!red.why.is_empty(), "{}: no reason the code fails it", red.name);
        assert!(!red.witness.is_empty(), "{}: no witness theorem", red.name);
    }
}

/// **Reds only change in review.** A count pinned here means a red cannot be dropped from the
/// ledger without the number moving. Update it in the same commit that adds or closes a red.
#[test]
fn red_count_is_pinned() {
    assert_eq!(REDS.len(), __COUNT__, "the number of reds changed; update this pin and say why");
}
"""


def slug(module: str, claim: str) -> str:
    """A name that is unambiguous, greppable, and a legal Rust identifier.

    The module is part of the name because two modules can record the same claim — "replay is
    idempotent" appears in more than one ledger — and a name alone would collide.
    """
    mod = re.sub(r"[^a-z0-9]+", "_", module.replace("Ferrosa.", "").lower()).strip("_")
    words = re.sub(r"[^a-z0-9]+", "_", claim.lower()).strip("_")
    words = re.sub(r"_+", "_", words)
    if words and words[0].isdigit():
        words = "n_" + words
    return f"{mod}__{words}"[:120].rstrip("_")


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def reds_of(data: dict) -> list[dict]:
    reds = []
    for area in data["areas"]:
        for item in area["items"]:
            if item.get("kind") == "met":
                continue
            reds.append({
                "name": slug(area["key"], item["claim"]),
                "module": area["key"],
                "claim": item["claim"],
                "why": item.get("why", ""),
                "witness": item["witness"],
            })
    reds.sort(key=lambda r: r["name"])
    return reds


def generate(data: dict) -> dict[str, str]:
    """The generated files, keyed by their path relative to the repo root."""
    reds = reds_of(data)
    rows = [DATA_HEADER]
    for r in reds:
        rows.append(
            "    Red {\n"
            f"        name: {rust_str(r['name'])},\n"
            f"        module: {rust_str(r['module'])},\n"
            f"        claim: {rust_str(r['claim'])},\n"
            f"        why: {rust_str(r['why'])},\n"
            f"        witness: {rust_str(r['witness'])},\n"
            "    },\n")
    rows.append("];\n")
    return {
        DATA: "".join(rows),
        TESTS: TESTS_TEMPLATE.replace("__COUNT__", str(len(reds))),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = generate(json.loads(SPECS.read_text()))
    n = files[DATA].count("    Red {")
    if args.check:
        stale = [p for p, text in files.items()
                 if not (ROOT / p).exists() or (ROOT / p).read_text() != text]
        for p in stale:
            sys.stderr.write(f"{p} is stale: run scripts/red_ledger.py\n")
        if stale:
            return 1
        print(f"red ledger: {n} reds, Rust side up to date")
        return 0
    for p, text in files.items():
        (ROOT / p).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / p).write_text(text)
    print(f"wrote {DATA} and {TESTS}: {n} reds")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
