#!/usr/bin/env python3
"""Generate the Rust side of the Lean red ledger.

Reads `specs/lean4/build/specs.json` — the documentation export, which carries every ledger claim
and, for the unmet ones, the witness theorem that proves the property absent — and writes
`red-ledger/tests/reds.rs`.

Each red claim becomes one `#[ignore]`d test whose name is derived from the module and the claim.
The test body is empty on purpose: while the claim is unmet there is nothing to assert, and a test
that asserts today's broken behaviour would have to be rewritten the moment somebody fixes it.
Un-ignoring the test is the act of fixing it.

Usage:
    red_ledger.py            write red-ledger/tests/reds.rs
    red_ledger.py --check    exit 1 if the file on disk is not what the ledger produces
"""

import argparse
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent                      # ferrosa/
SPECS = ROOT / "specs/lean4/build/specs.json"
OUT = ROOT / "red-ledger/tests/reds.rs"

HEADER = """\
// @generated by scripts/red_ledger.py from specs/lean4/build/specs.json — do not edit by hand.
//
// One test per red item in the Lean ledgers. While the claim is unmet the test is `#[ignore]`d and
// its body is empty: it names the gap and nothing else. Fixing the code means removing `#[ignore]`
// and stating what now holds; closing the item in Lean means the generator stops emitting it here.
//
//     cargo test -p red-ledger                       the join is consistent
//     cargo test -p red-ledger -- --include-ignored  every red, so you can watch one turn green

// The double underscore separates the Lean module from the claim; it is deliberate, not a typo.
#![allow(non_snake_case)]

/// (test name, Lean module, the claim, why the code does not meet it, the theorem that proves it)
pub type Red = (&'static str, &'static str, &'static str, &'static str, &'static str);

pub const REDS: &[Red] = &[
"""


def slug(module: str, claim: str) -> str:
    """A test name that is unambiguous, greppable, and a legal Rust identifier.

    The module is part of the name because two modules can record the same claim — "replay is
    idempotent" appears in more than one ledger — and a name alone would collide.
    """
    mod = re.sub(r"[^a-z0-9]+", "_", module.replace("Ferrosa.", "").lower()).strip("_")
    words = re.sub(r"[^a-z0-9]+", "_", claim.lower()).strip("_")
    words = re.sub(r"_+", "_", words)
    if words and words[0].isdigit():
        words = "n_" + words
    return f"{mod}__{words}"[:120].rstrip("_")


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def generate() -> str:
    data = json.loads(SPECS.read_text())
    reds = []
    for area in data["areas"]:
        for item in area["items"]:
            if item.get("kind") == "met":
                continue
            reds.append({
                "name": slug(area["key"], item["claim"]),
                "module": area["key"],
                "claim": item["claim"],
                "why": item.get("why", ""),
                "witness": item["witness"],
            })
    reds.sort(key=lambda r: r["name"])

    out = [HEADER]
    for r in reds:
        out.append(f"    ({rust_str(r['name'])}, {rust_str(r['module'])}, {rust_str(r['claim'])}, "
                   f"{rust_str(r['why'])}, {rust_str(r['witness'])}),\n")
    out.append("];\n")
    out.append(TESTS_TAIL)
    for r in reds:
        doc = "".join(f"/// {line.strip()}\n" for line in _wrap(f"RED — {r['claim']}", 92))
        why = "".join(f"/// {line.strip()}\n" for line in _wrap(f"Why: {r['why']}", 92))
        wit = "".join(f"/// {line.strip()}\n" for line in _wrap(f"Witness: {r['witness']}", 92))
        claim = r["claim"].replace('"', '\\"')
        out.append(f"""
{doc}{why}{wit}/// Module: {r['module']}
#[test]
#[ignore = "RED: the code does not yet meet this claim — see the Lean witness in the doc comment"]
fn {r['name']}() {{
    // It panics rather than passing vacuously: removing `#[ignore]` without fixing the code has to
    // fail, or the harness would report a green that means nothing. Replace this with the assertion
    // the claim actually needs.
    panic!("RED: {claim}");
}}
""")
    return "".join(out)


def _wrap(text: str, width: int) -> list[str]:
    words, lines, line = text.split(), [], ""
    for w in words:
        if len(line) + len(w) + 1 > width:
            lines.append(line)
            line = w
        else:
            line = f"{line} {w}".strip()
    if line:
        lines.append(line)
    return lines


TESTS_TAIL = """

/// **The join holds.** Every red the generator emitted has a test function in this file, and every
/// `#[ignore]`d test corresponds to a red. The check is against this file's own text, so it cannot
/// pass by consulting a stale copy of the ledger.
#[test]
fn every_red_has_a_test_and_every_test_a_red() {
    let src = include_str!("reds.rs");
    let declared: Vec<&str> = src
        .lines()
        .filter_map(|l| l.strip_prefix("fn "))
        .filter_map(|l| l.split('(').next())
        .collect();

    let mut missing = 0;
    for (name, module, claim, _, _) in REDS {
        if !declared.contains(name) {
            eprintln!("red with no test: {name} ({module}: {claim})");
            missing += 1;
        }
    }

    let red_names: Vec<&str> = REDS.iter().map(|r| r.0).collect();
    // the two functions that are this file's own tests, not reds
    let meta = ["every_red_has_a_test_and_every_test_a_red", "red_count_is_pinned"];
    let mut stray = 0;
    for name in &declared {
        if meta.contains(name) {
            continue;
        }
        if !red_names.contains(name) {
            eprintln!("test with no red: {name} — either the claim was closed in Lean and the file is stale, or the test no longer matches any ledger item");
            stray += 1;
        }
    }

    assert_eq!(missing + stray, 0, "the Lean red ledger and the Rust tests disagree; run scripts/red_ledger.py");
}

/// **Reds only shrink.** A count pinned here means a red cannot be quietly dropped from the ledger
/// without the number moving, and a count that grows is a change somebody should have to see in
/// review. Update the number in the same commit that adds or closes a red.
#[test]
fn red_count_is_pinned() {
    assert_eq!(REDS.len(), __COUNT__, "the number of reds changed; update this pin and say why");
}
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = generate()
    n = text.count("#[ignore = \"RED:")
    text = text.replace("__COUNT__", str(n))
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.stderr.write(f"{OUT.relative_to(ROOT)} is stale: run scripts/red_ledger.py\n")
            return 1
        print(f"red ledger: {n} reds, Rust side up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {n} reds")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
