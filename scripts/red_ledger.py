#!/usr/bin/env python3
"""Generate the Rust side of the Lean red ledger.

Reads `specs/lean4/build/specs.json` -- the documentation export, which carries every ledger claim
and, for the unmet ones, the witness theorem that proves the property absent -- and writes:

  red-ledger/src/reds.rs     the table: one `Red` per unmet claim, named by module and claim
  red-ledger/src/met.rs      the table: one `Met` per discharged claim, with the theorem that proves it
  red-ledger/tests/reds.rs   tests that assert things about both tables on every run

A red is data, not a test. The first version emitted one empty `#[ignore]`d test per red, which
shipped the join as 59 waivers; an ignored test that asserts nothing is a waiver whatever it is meant
to document. Closing a red is: write the real test in the crate that owns the code, then flip the
ledger item to `.met` in Lean, which drops the row from this table and moves the pinned count.

Usage:
    red_ledger.py            write both files
    red_ledger.py --check    exit 1 if either file on disk is not what the ledger produces
"""

import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent                      # ferrosa/
SPECS = ROOT / "specs/lean4/build/specs.json"
DATA = "red-ledger/src/reds.rs"
MET = "red-ledger/src/met.rs"
TESTS = "red-ledger/tests/reds.rs"

GENERATED = "// @generated by scripts/red_ledger.py from specs/lean4/build/specs.json — do not edit by hand.\n"

DATA_HEADER = GENERATED + """\
//
// One row per red item in the Lean ledgers. A row leaves this table when its Lean item is closed,
// which happens after the owning crate has a test that pins the claim.

/// Which kind of claim a row is. See `Ferrosa.Ledger.Claim`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ClaimKind {
    /// Proved of a model; carries no claim about the shipping implementation.
    Design,
    /// A claim about the shipping implementation.
    Code,
}

/// One unmet claim of the Lean specification.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Red {
    /// `<module>__<claim>`, unique across the corpus; the name a closing test takes.
    pub name: &'static str,
    /// The Lean module whose ledger holds the claim.
    pub module: &'static str,
    /// The claim, verbatim from the ledger.
    pub claim: &'static str,
    /// Why the code does not meet it, verbatim from the ledger.
    pub why: &'static str,
    /// The theorem that proves the property absent.
    pub witness: &'static str,
    /// Whether this row is about the code or about a model.
    pub claim_kind: ClaimKind,
}

pub const REDS: &[Red] = &[
"""

MET_HEADER = GENERATED + """\
//
// One row per discharged claim, so the side a reader is meant to TRUST is machine-readable too. A
// red row says what is broken; a row here says what holds, and whether it holds of the code or only
// of a model. Reading only the red table is how a stale model survives: `Ferrosa.Storage.Recovery`
// proved corruption is undetectable while the real record carried a CRC.

use crate::ClaimKind;

/// One discharged claim of the Lean specification.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Met {
    /// `<module>__<claim>`, unique across the corpus.
    pub name: &'static str,
    /// The Lean module whose ledger holds the claim.
    pub module: &'static str,
    /// The claim, verbatim from the ledger.
    pub claim: &'static str,
    /// The theorem that proves it.
    pub proof: &'static str,
    /// Whether this holds of the code, or only of a model.
    pub claim_kind: ClaimKind,
}

pub const METS: &[Met] = &[
"""

TESTS_TEMPLATE = GENERATED + """\
//
// Assertions about the red table. They run on every `cargo test`; nothing here is ignored.

use red_ledger::{ClaimKind, METS, REDS};
use std::collections::HashSet;

/// **Every red is addressable.** Names are unique, so a closing test can take a red's name without
/// ambiguity, and each is a legal Rust identifier, so it can be that test's function name.
#[test]
fn red_names_are_unique_identifiers() {
    let mut seen = HashSet::new();
    for red in REDS {
        assert!(
            seen.insert(red.name),
            "two reds share the name {}",
            red.name
        );
        assert!(
            red.name
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_'),
            "{} is not a snake_case identifier",
            red.name
        );
    }
}

/// **Every red carries its evidence.** A red without a reason or a witness theorem is a claim
/// nobody can check, so the row is refused rather than carried.
#[test]
fn every_red_names_its_reason_and_witness() {
    for red in REDS {
        assert!(!red.claim.is_empty(), "{}: empty claim", red.name);
        assert!(
            !red.why.is_empty(),
            "{}: no reason the code fails it",
            red.name
        );
        assert!(!red.witness.is_empty(), "{}: no witness theorem", red.name);
    }
}

/// **Every discharged row names its proof.** A `.met` row with no theorem is the same waiver a red
/// with no witness is, only harder to notice because it reads as good news.
#[test]
fn every_met_names_its_proof() {
    for met in METS {
        assert!(!met.claim.is_empty(), "{}: empty claim", met.name);
        assert!(!met.proof.is_empty(), "{}: no theorem proves it", met.name);
    }
}

/// **A name is either red or discharged, never both.** The two tables partition the corpus, so a
/// row cannot be dropped by being written twice.
#[test]
fn red_and_met_tables_are_disjoint() {
    let reds: HashSet<&str> = REDS.iter().map(|r| r.name).collect();
    for met in METS {
        assert!(
            !reds.contains(met.name),
            "{} is both red and discharged",
            met.name
        );
    }
}

/// **The discharged count is pinned.** Same rule as the reds: closing a claim moves this number in
/// the same commit, so a `.met` row cannot vanish silently.
#[test]
fn met_count_is_pinned() {
    assert_eq!(
        METS.len(),
        __MET_COUNT__,
        "the number of discharged claims changed; update this pin and say why"
    );
}

/// **The `code:` marker is load-bearing, so it must actually be reachable.** A `ClaimKind::Code` row is
/// the only kind a reader may act on as assurance. If the marker stopped matching — a rename, a
/// missing prefix on a flip, a generator bug — every row would silently become `Design` and nothing
/// would fail. This test makes that a build failure instead: at least one row of each kind must
/// exist in the corpus.
#[test]
fn both_claim_kinds_are_represented() {
    let reds_code = REDS
        .iter()
        .filter(|r| r.claim_kind == ClaimKind::Code)
        .count();
    let mets_code = METS
        .iter()
        .filter(|m| m.claim_kind == ClaimKind::Code)
        .count();
    assert!(
        reds_code > 0,
        "no red row is marked `code:`, so the marker is not matching and every row would \
         read as a design claim"
    );
    assert!(
        mets_code > 0,
        "no discharged row is marked `code:`. A `.met` row is only assurance about the \
         shipping code when it carries the marker; verify a claim against the code and rename it \
         `code: …` in the same commit that flips it"
    );
}

/// **Reds only change in review.** A count pinned here means a red cannot be dropped from the
/// ledger without the number moving. Update it in the same commit that adds or closes a red.
#[test]
fn red_count_is_pinned() {
    assert_eq!(
        REDS.len(),
        __COUNT__,
        "the number of reds changed; update this pin and say why"
    );
}
"""


def slug(module: str, claim: str) -> str:
    """A name that is unambiguous, greppable, and a legal Rust identifier.

    The module is part of the name because two modules can record the same claim — "replay is
    idempotent" appears in more than one ledger — and a name alone would collide.
    """
    mod = re.sub(r"[^a-z0-9]+", "_", module.replace("Ferrosa.", "").lower()).strip("_")
    words = re.sub(r"[^a-z0-9]+", "_", claim.lower()).strip("_")
    words = re.sub(r"_+", "_", words)
    if words and words[0].isdigit():
        words = "n_" + words
    return f"{mod}__{words}"[:120].rstrip("_")


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def reds_of(data: dict) -> list[dict]:
    reds = []
    for area in data["areas"]:
        for item in area["items"]:
            if item.get("kind") == "met":
                continue
            reds.append({
                "name": slug(area["key"], item["claim"]),
                "module": area["key"],
                "claim": item["claim"],
                "why": item.get("why", ""),
                "witness": item["witness"],
                "claim_kind": item.get("claimKind", "design"),
            })
    reds.sort(key=lambda r: r["name"])
    return reds


def mets_of(data: dict) -> list[dict]:
    """The discharged claims, so the side a reader trusts is machine-readable too."""
    mets = []
    for area in data["areas"]:
        for item in area["items"]:
            if item.get("kind") != "met":
                continue
            mets.append({
                "name": slug(area["key"], item["claim"]),
                "module": area["key"],
                "claim": item["claim"],
                "proof": item.get("proof", ""),
                "claim_kind": item.get("claimKind", "design"),
            })
    mets.sort(key=lambda m: m["name"])
    return mets


def kind_variant(kind: str) -> str:
    return "Code" if kind == "code" else "Design"


def rustfmt_clean(text: str) -> str:
    """The generated text must already be what rustfmt would write.

    CI runs both `cargo fmt --check` and `red_ledger.py --check`, so if rustfmt would rewrite a
    generated file then one of the two must fail -- formatting breaks the staleness check, and not
    formatting breaks the format check. Neither can be given up, so the generator emits formatted
    text and both agree by construction.

    Normalising here rather than hand-matching rustfmt's line-breaking is deliberate: rustfmt
    collapses a one-element array to `&[Red {` and keeps a 352-element one multi-line, so no fixed
    emitter shape is clean at every size. The test suite pins this by generating from a one-row
    synthetic ledger.
    """
    rustfmt = shutil.which("rustfmt")
    if rustfmt is None:
        return text
    out = subprocess.run([rustfmt, "--edition", "2021", "--emit", "stdout"],
                         input=text, capture_output=True, text=True)
    if out.returncode != 0:
        sys.stderr.write(f"rustfmt failed on generated text: {out.stderr}\n")
        raise SystemExit(2)
    return out.stdout


def generate(data: dict) -> dict[str, str]:
    """The generated files, keyed by their path relative to the repo root."""
    reds = reds_of(data)
    rows = [DATA_HEADER]
    for r in reds:
        rows.append(
            "    Red {\n"
            f"        name: {rust_str(r['name'])},\n"
            f"        module: {rust_str(r['module'])},\n"
            f"        claim: {rust_str(r['claim'])},\n"
            f"        why: {rust_str(r['why'])},\n"
            f"        witness: {rust_str(r['witness'])},\n"
            f"        claim_kind: ClaimKind::{kind_variant(r['claim_kind'])},\n"
            "    },\n")
    rows.append("];\n")

    mets = mets_of(data)
    mrows = [MET_HEADER]
    for m in mets:
        mrows.append(
            "    Met {\n"
            f"        name: {rust_str(m['name'])},\n"
            f"        module: {rust_str(m['module'])},\n"
            f"        claim: {rust_str(m['claim'])},\n"
            f"        proof: {rust_str(m['proof'])},\n"
            f"        claim_kind: ClaimKind::{kind_variant(m['claim_kind'])},\n"
            "    },\n")
    mrows.append("];\n")

    tests = (TESTS_TEMPLATE
             .replace("__COUNT__", str(len(reds)))
             .replace("__MET_COUNT__", str(len(mets))))
    return {p: rustfmt_clean(t) for p, t in
            ((DATA, "".join(rows)), (MET, "".join(mrows)), (TESTS, tests))}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = generate(json.loads(SPECS.read_text()))
    n = files[DATA].count("    Red {")
    if args.check:
        stale = [p for p, text in files.items()
                 if not (ROOT / p).exists() or (ROOT / p).read_text() != text]
        for p in stale:
            sys.stderr.write(f"{p} is stale: run scripts/red_ledger.py\n")
        if stale:
            return 1
        print(f"red ledger: {n} reds, Rust side up to date")
        return 0
    for p, text in files.items():
        (ROOT / p).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / p).write_text(text)
    print(f"wrote {DATA} and {TESTS}: {n} reds")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
