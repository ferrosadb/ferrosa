"""scope.toml: the extraction scope is explicit, checked in, and machine-checked.

The scope has three kinds of entry and every one of them needs a reason, an owner and a date:

  [[crate]] kind="own"       a ferrosa crate -- in scope because it is our code
  [[crate]] kind="critical"  a dependency we reason about deliberately
  [blanket]                  the one blanket exclusion: every other dependency
  [[item]]                   an item excluded inside an included crate, e.g. a derive's visitor

The evidence for an item exclusion is the emitted Lean, not a flag somebody passed. charon's
`--opaque` makes aeneas emit `def ... := sorry` for the item, and the declaration carries its
charon name pattern in an `@[rust_fun "..."]` attribute. So "what was assumed" is a fact a reader
can grep for in a committed file, and this checker reads that same file:

  SILENT  an assumption in the Lean that no scope entry explains  (the failure mode: silence)
  STALE   a scope entry that no longer matches anything in the Lean (the file rotted)
  UNSCOPED  a workspace crate with no scope decision at all
  NO-REASON / NO-OWNER / NO-DATE  an entry nobody is accountable for
  BLANKET   more than the one blanket exclusion the design allows

Nothing here needs charon, aeneas or a network: it compares committed files, so it runs on every
pull request and costs milliseconds.
"""

import importlib.util
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SCRIPT = REPO / "specs" / "lean4-rust" / "scope-check.py"


def load_checker():
    spec = importlib.util.spec_from_file_location("scope_check", SCRIPT)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {SCRIPT} as a module")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


sc = load_checker()

SCOPE = """\
schema = 1

[[crate]]
name = "demo-crate"
kind = "own"
reason = "our code; the metadata contract lives here"
owner = "bkearns"
date = "2026-11-04"

[[crate]]
name = "other-crate"
kind = "own"
reason = "our code"
owner = "bkearns"
date = "2026-11-04"

[[crate]]
name = "serde"
kind = "critical"
reason = "the serialized form of the metadata is a wire contract"
owner = "bkearns"
date = "2026-11-04"

[blanket]
reason = "every dependency not named above is out of scope: we reason about ferrosa and the few crates it depends on, not about its dependency tree"
owner = "bkearns"
date = "2026-11-04"

[[item]]
crate = "demo-crate"
pattern = "{impl serde_core::de::Deserialize<demo_crate::metadata::Thing>}"
kind = "opaque"
reason = "serde's derived visitor walks 12 fallible field steps: 2^12 paths, and the item is generated code, not business logic"
owner = "bkearns"
date = "2026-11-04"
"""

LEAN = """/- Generated by aeneas. -/

@[rust_fun "core::option::Option::map"]
def core.option.Option.map {T U : Type _} (f : T → U) (o : core.option.Option T) :
  core.option.Option U := sorry

/-- Derived implementation of `Deserialize` for `Thing`. -/
@[rust_fun "demo_crate::metadata::_::{impl serde_core::de::Deserialize for demo_crate::metadata::Thing}::deserialize"]
def Thing.Insts.CoreSerdeDeserialize.deserialize
  : core.result.Result Thing core.serde.Error
  := sorry

def demo_crate.metadata.Thing.keyspace (self : Thing) : Std.String :=
  self.keyspace
"""

MODULES = """\
# module   crate        sources     charon scope
Demo       demo-crate   src/lib.rs  demo_crate::*
"""

# The ledger row that matches the `:= sorry` declaration in LEAN: the assumption is visible in the
# emitted module, so the row says so. `record` writes these from the artifacts; the fixture writes
# the same columns by hand because the point here is the checker, not the writer.
LEDGER = ("# module\tcrate\tpattern\tevidence\tdate\n"
          "Demo\tdemo-crate\t{impl serde_core::de::Deserialize<demo_crate::metadata::Thing>}"
          "\tin-lean\t2026-11-04\n")

CARGO = """\
[workspace]
members = ["demo-crate", "other-crate"]
resolver = "2"
"""

CARGO_LOCK = """\
version = 3

[[package]]
name = "demo-crate"
version = "0.1.0"

[[package]]
name = "other-crate"
version = "0.1.0"

[[package]]
name = "serde"
version = "1.0.219"
"""


class Fixture:
    """A miniature repo: two crates, one generated module, one scope file."""

    def __init__(self, tmp: Path):
        self.root = tmp
        (self.root / "specs" / "lean4-rust" / "FerrosaRust").mkdir(parents=True)
        for crate in ("demo-crate", "other-crate"):
            (self.root / crate / "src").mkdir(parents=True)
            (self.root / crate / "src" / "lib.rs").write_text("pub fn f() {}\n")
            (self.root / crate / "Cargo.toml").write_text(
                f'[package]\nname = "{crate}"\nversion = "0.1.0"\n')
        (self.root / "Cargo.toml").write_text(CARGO)
        (self.root / "Cargo.lock").write_text(CARGO_LOCK)
        spec = self.root / "specs" / "lean4-rust"
        (spec / "scope.toml").write_text(SCOPE)
        (spec / "modules.txt").write_text(MODULES)
        (spec / "scope.lock").write_text(LEDGER)
        (spec / "FerrosaRust" / "Demo.lean").write_text(LEAN)

    def scope(self):
        return self.root / "specs" / "lean4-rust" / "scope.toml"

    def ledger(self):
        return self.root / "specs" / "lean4-rust" / "scope.lock"

    def lean(self, module="Demo"):
        return self.root / "specs" / "lean4-rust" / "FerrosaRust" / f"{module}.lean"

    def run(self, *args):
        return subprocess.run([sys.executable, str(SCRIPT), *args, "--root", str(self.root)],
                              capture_output=True, text=True)


class ScopeRules(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.fx = Fixture(self.tmp)

    def tearDown(self):
        shutil.rmtree(self.tmp)

    def check(self):
        return self.fx.run("check")

    def assertFails(self, code):
        out = self.check()
        self.assertEqual(out.returncode, 1, out.stdout + out.stderr)
        self.assertIn(code, out.stdout)

    def edit_scope(self, old, new):
        text = self.fx.scope().read_text()
        self.assertIn(old, text)
        self.fx.scope().write_text(text.replace(old, new, 1))

    def test_a_scope_that_explains_every_assumption_passes(self):
        out = self.check()
        self.assertEqual(out.returncode, 0, out.stdout + out.stderr)
        self.assertIn("1 assumption", out.stdout)

    def test_an_assumption_in_the_lean_that_no_scope_entry_explains_fails(self):
        # The failure this whole file exists for: code was left out of the Lean and nothing says
        # so. Adding a second own-crate `:= sorry` declaration is exactly what a silent exclusion
        # looks like after the fact.
        self.fx.lean().write_text(LEAN + """
@[rust_fun "demo_crate::metadata::validate::check"]
def demo_crate.metadata.validate.check (x : Thing) : core.result.Result Unit Error := sorry
""")
        self.assertFails("SILENT")
        self.assertIn("demo_crate::metadata::validate::check", self.check().stdout)

    def test_a_scope_item_that_no_lean_declaration_carries_fails(self):
        # The Rust moved, the derived impl was renamed, and the entry now excludes nothing while
        # still reading as an assumption someone made.
        self.edit_scope('pattern = "{impl serde_core::de::Deserialize<demo_crate::metadata::Thing>}"',
                        'pattern = "{impl serde_core::de::Deserialize<demo_crate::metadata::Renamed>}"')
        self.assertFails("STALE")

    def test_a_ferrosa_crate_neither_included_nor_excluded_fails(self):
        self.edit_scope("""\
[[crate]]
name = "other-crate"
kind = "own"
reason = "our code"
owner = "bkearns"
date = "2026-11-04"

""", "")
        self.assertFails("UNSCOPED")
        self.assertIn("other-crate", self.check().stdout)

    def test_an_item_without_a_reason_fails(self):
        self.edit_scope('reason = "serde\'s derived visitor walks 12 fallible field steps: '
                        '2^12 paths, and the item is generated code, not business logic"',
                        'reason = ""')
        self.assertFails("NO-REASON")

    def test_an_item_without_an_owner_or_a_date_fails(self):
        self.edit_scope("""\
reason = "serde's derived visitor walks 12 fallible field steps: 2^12 paths, and the item is generated code, not business logic"
owner = "bkearns"
date = "2026-11-04"
""", """\
reason = "serde's derived visitor walks 12 fallible field steps: 2^12 paths, and the item is generated code, not business logic"
""")
        out = self.check()
        self.assertEqual(out.returncode, 1, out.stdout)
        self.assertIn("NO-OWNER", out.stdout)
        self.assertIn("NO-DATE", out.stdout)

    def test_a_second_blanket_exclusion_fails(self):
        # `[blanket]` is the one place a whole category is dismissed. A wildcard crate entry is
        # the same decision wearing a per-crate shape, and two of them means nobody can say what
        # is in scope.
        self.edit_scope('[blanket]', '[[crate]]\nname = "*"\nkind = "dependency"\n'
                        'reason = "everything else"\nowner = "bkearns"\n'
                        'date = "2026-11-04"\n\n[blanket]')
        self.assertFails("BLANKET")

    def test_a_missing_blanket_exclusion_fails(self):
        # Without it, "everything else is out of scope" is an unstated assumption: a new
        # dependency would silently be neither included nor excluded.
        self.edit_scope("[blanket]\nreason = \"every dependency not named above is out of scope: we "
                        "reason about ferrosa and the few crates it depends on, not about its "
                        "dependency tree\"\nowner = \"bkearns\"\ndate = \"2026-11-04\"\n", "")
        self.assertFails("BLANKET")

    def test_an_item_can_only_be_declared_opaque(self):
        # `--exclude` removes an item without leaving a trace, so an entry that asked for it
        # would be a silent exclusion in a file that claims to make exclusions visible.
        self.edit_scope('kind = "opaque"', 'kind = "exclude"')
        self.assertFails("NOT-VISIBLE")

    def test_a_critical_dependency_that_is_not_a_dependency_fails(self):
        self.edit_scope('name = "serde"', 'name = "serde-does-not-exist"')
        self.assertFails("STALE-CRATE")

    def test_a_module_for_a_crate_that_is_not_in_scope_fails(self):
        # modules.txt is the other way into the extraction: a row there extracts a crate even if
        # the scope file never mentions it, and nothing else would notice a crate drifting in.
        (self.fx.root / "specs/lean4-rust/modules.txt").write_text(
            MODULES + "Stray stray-crate src/lib.rs stray_crate::*\n")
        self.fx.lean("Stray").write_text("-- nothing generated\n")
        self.assertFails("UNSCOPED-CRATE")


class LedgerRules(unittest.TestCase):
    """scope.lock: the record for an assumption the Lean cannot show.

    aeneas drops an opaque trait-impl method that nothing reachable calls, so for the derived
    `Deserialize` in `ferrosa-view` there is no `:= sorry` to point at. The ledger is then the only
    record, which is why it is generated from charon's llbc and the emitted Lean and checked
    against the scope file rather than trusted.
    """

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.fx = Fixture(self.tmp)

    def tearDown(self):
        shutil.rmtree(self.tmp)

    def out(self):
        return self.fx.run("check")

    def test_a_visible_assumption_without_a_ledger_row_fails(self):
        self.fx.ledger().write_text("# module\tcrate\tpattern\tevidence\tdate\n")
        found = self.out()
        self.assertEqual(found.returncode, 1, found.stdout)
        self.assertIn("LEDGER", found.stdout)

    def test_a_row_claiming_the_lean_carries_it_when_it_does_not_fails(self):
        # The generated file was regenerated and the declaration went away; a row that still says
        # `in-lean` is a claim about a file that no longer says it.
        self.fx.lean().write_text(LEAN.replace(
            'def Thing.Insts.CoreSerdeDeserialize.deserialize\n'
            '  : core.result.Result Thing core.serde.Error\n'
            '  := sorry\n', ''))
        found = self.out()
        self.assertEqual(found.returncode, 1, found.stdout)
        self.assertIn("LEDGER", found.stdout)

    def test_a_row_for_a_module_with_no_generated_file_fails(self):
        self.fx.lean().unlink()
        found = self.out()
        self.assertEqual(found.returncode, 1, found.stdout)
        self.assertIn("LEDGER", found.stdout)

    def test_a_row_no_scope_entry_explains_fails(self):
        # The ledger is generated, but generated from a run somebody configured: a row here that
        # the scope file does not explain is a silent exclusion with a paper trail.
        self.fx.ledger().write_text(LEDGER + (
            "Demo\tdemo-crate\tdemo_crate::metadata::validate::check\tnot-emitted\t2026-11-04\n"))
        found = self.out()
        self.assertEqual(found.returncode, 1, found.stdout)
        self.assertIn("SILENT", found.stdout)

    def test_two_rows_for_one_entry_fail(self):
        self.fx.ledger().write_text(LEDGER + (
            "Demo\tdemo-crate\t{impl serde_core::de::Deserialize<demo_crate::metadata::Thing>}"
            "\tin-lean\t2026-11-04\n"))
        found = self.out()
        self.assertEqual(found.returncode, 1, found.stdout)
        self.assertIn("LEDGER", found.stdout)

    def test_an_assumption_the_lean_cannot_carry_passes_once_recorded(self):
        # The real case: the exclusion worked (charon made the item opaque) and aeneas emitted no
        # declaration for it. The row says `not-emitted`, and that is a checkable statement.
        self.fx.lean().write_text(LEAN.replace(
            'def Thing.Insts.CoreSerdeDeserialize.deserialize\n'
            '  : core.result.Result Thing core.serde.Error\n'
            '  := sorry\n', ''))
        self.fx.ledger().write_text(
            "# module\tcrate\tpattern\tevidence\tdate\n"
            "Demo\tdemo-crate\t{impl serde_core::de::Deserialize<demo_crate::metadata::Thing>}"
            "\tnot-emitted\t2026-11-04\n")
        out = self.out()
        self.assertEqual(out.returncode, 0, out.stdout)

    def test_record_writes_the_evidence_from_the_tools_output(self):
        # `record` asks charon's llbc what the entry still matches and the Lean what it produced.
        # A stub charon stands in for the real one so the test needs no toolchain: what is under
        # test is that the row comes from the artifacts, not from the caller.
        stub = self.tmp / "charon"
        stub.write_text(
            "#!/bin/sh\n"
            "printf '%s\\n' '// Full name: demo_crate::metadata::_#9::{impl "
            "serde_core::de::Deserialize<demo_crate::metadata::Thing>}::deserialize'\n")
        stub.chmod(0o755)
        llbc = self.tmp / "demo.llbc"
        llbc.write_text("{}")
        self.fx.ledger().write_text("")
        out = subprocess.run([sys.executable, str(SCRIPT), "record", "Demo", "--llbc", str(llbc),
                              "--charon", str(stub), "--root", str(self.fx.root)],
                             capture_output=True, text=True)
        self.assertEqual(out.returncode, 0, out.stdout + out.stderr)
        self.assertIn("in-lean", self.fx.ledger().read_text())

    def test_record_fails_when_the_entry_matches_nothing(self):
        stub = self.tmp / "charon"
        stub.write_text("#!/bin/sh\nprintf '%s\\n' '// Full name: demo_crate::other::f'\n")
        stub.chmod(0o755)
        llbc = self.tmp / "demo.llbc"
        llbc.write_text("{}")
        out = subprocess.run([sys.executable, str(SCRIPT), "record", "Demo", "--llbc", str(llbc),
                              "--charon", str(stub), "--root", str(self.fx.root)],
                             capture_output=True, text=True)
        self.assertEqual(out.returncode, 1, out.stdout)
        self.assertIn("STALE", out.stdout)


class PatternClaims(unittest.TestCase):
    """`claims`: does a scope pattern explain an assumption the Lean actually carries?

    charon's rule (name_matcher/mod.rs) is that a pattern matches a prefix of the item's name, and
    that a pattern starting with an impl block matches the rightmost impl block in the name. The
    scope file has to be read with the same rule, or an entry that charon honoured would look
    stale here and a person would "fix" it by deleting a real assumption.
    """

    DERIVED = ("demo_crate::metadata::_::{impl serde_core::de::Deserialize for "
               "demo_crate::metadata::Thing}::deserialize")

    def test_an_impl_pattern_claims_the_derived_method(self):
        self.assertTrue(sc.claims(
            "{impl serde_core::de::Deserialize<demo_crate::metadata::Thing>}", self.DERIVED))

    def test_an_impl_pattern_without_the_type_still_claims_it(self):
        self.assertTrue(sc.claims("{impl serde_core::de::Deserialize}", self.DERIVED))

    def test_an_impl_pattern_for_another_type_does_not_claim_it(self):
        self.assertFalse(sc.claims(
            "{impl serde_core::de::Deserialize<demo_crate::metadata::Other>}", self.DERIVED))

    def test_a_module_pattern_claims_an_item_below_it(self):
        self.assertTrue(sc.claims("demo_crate::metadata", self.DERIVED))

    def test_a_module_pattern_does_not_claim_something_else_entirely(self):
        self.assertFalse(sc.claims("demo_crate::other", self.DERIVED))

    def test_a_glob_elem_matches_something_the_pattern_cannot_name(self):
        # The derive's impl block sits under an anonymous const whose name (`_#9`) has a
        # disambiguator charon's pattern parser cannot spell, so `_` is the only way to write it.
        self.assertTrue(sc.claims("demo_crate::metadata::_",
                                  "demo_crate::metadata::_#9::validate"))

    def test_a_trailing_glob_matches_any_tail(self):
        self.assertTrue(sc.claims("demo_crate::metadata::_",
                                  "demo_crate::metadata::Thing::method"))

    def test_generics_in_the_item_name_do_not_defeat_the_comparison(self):
        self.assertTrue(sc.claims(
            "{impl core::fmt::Display<demo_crate::metadata::Thing>}",
            "{impl core::fmt::Display for demo_crate::metadata::Thing}::fmt"))


class LeanScanner(unittest.TestCase):
    """The `:= sorry` declarations a module carries, with the charon pattern above each."""

    def test_it_finds_the_foreign_and_the_local_assumption(self):
        decls = sc.lean_decls(LEAN)
        patterns = [d["pattern"] for d in decls if d["sorry"]]
        self.assertEqual(patterns, ["core::option::Option::map",
                                    "demo_crate::metadata::_::{impl serde_core::de::"
                                    "Deserialize for demo_crate::metadata::Thing}::deserialize"])

    def test_a_definition_with_a_body_is_not_an_assumption(self):
        decls = sc.lean_decls(LEAN)
        keyspace = [d for d in decls if "keyspace" in d["name"]]
        self.assertEqual(len(keyspace), 1)
        self.assertFalse(keyspace[0]["sorry"])

    def test_comments_and_docstrings_do_not_break_the_scan(self):
        decls = sc.lean_decls(LEAN)
        self.assertTrue(all(d["name"] for d in decls))


class CommittedScope(unittest.TestCase):
    """The checked-in scope file, not a fixture."""

    def test_the_committed_scope_explains_every_committed_assumption(self):
        out = subprocess.run([sys.executable, str(SCRIPT), "check"],
                             capture_output=True, text=True, cwd=REPO)
        self.assertEqual(out.returncode, 0, out.stdout + out.stderr)

    def test_every_workspace_crate_is_named(self):
        scope = sc.load_scope(REPO / "specs" / "lean4-rust" / "scope.toml")
        named = {c["name"] for c in scope["crates"]}
        members = set(sc.workspace_members(REPO))
        self.assertEqual(members - named, set())


